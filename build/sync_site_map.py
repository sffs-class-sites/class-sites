#!/usr/bin/env python3
"""Turn the Site Map sheet into site-map.yaml, the generated copy agents and jobs read.

  python3 build/sync_site_map.py --csv tests/fixtures/site-map.csv   # from a CSV export
  python3 build/sync_site_map.py --sheet <spreadsheet id>            # from Google Sheets

--sheet signs in as the Drive bot: GOOGLE_SERVICE_ACCOUNT_JSON holds its key (an
Actions secret, never committed). Reads the first tab, columns A:J.

Fails closed (CLAUDE.md §2): a source is `publishable` only when Sync is Yes and it has a
Drive file ID, a publish list, Approved by and Approved on. Every other source is listed
with the reason it is blocked, and jobs that publish must skip it. Exits 1 on a malformed
sheet (missing columns, duplicate embeds, unknown key) without writing anything.
"""
import argparse
import csv
import io
import json
import os
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "site-map.yaml"
COLUMNS = ["Source", "Embed", "Drive file ID", "Shape", "Key", "Publish list",
           "Approved by", "Approved on", "Sync", "Notes"]
KEYS = {"grade", "school-year", "class"}


def from_sheet(sheet_id):
    from google.oauth2 import service_account
    from google.auth.transport.requests import AuthorizedSession
    info = json.loads(os.environ["GOOGLE_SERVICE_ACCOUNT_JSON"])
    creds = service_account.Credentials.from_service_account_info(
        info, scopes=["https://www.googleapis.com/auth/spreadsheets.readonly"])
    r = AuthorizedSession(creds).get(f"https://sheets.googleapis.com/v4/spreadsheets/{sheet_id}/values/A:J")
    r.raise_for_status()
    return r.json().get("values", [])


def from_csv(path):
    return list(csv.reader(io.StringIO(pathlib.Path(path).read_text())))


def parse(rows):
    """rows: header + data rows as lists of strings. Returns (sources, errors)."""
    if not rows:
        return [], ["the sheet is empty"]
    header = [h.strip() for h in rows[0]]
    missing = [c for c in COLUMNS if c not in header]
    if missing:
        return [], [f"missing columns: {', '.join(missing)}"]
    idx = {c: header.index(c) for c in COLUMNS}
    sources, errors, seen = [], [], set()
    for n, row in enumerate(rows[1:], start=2):
        cell = lambda c: (row[idx[c]] if idx[c] < len(row) else "").strip()
        if not any(cell(c) for c in COLUMNS):
            continue
        embed, key = cell("Embed"), cell("Key")
        if not embed:
            errors.append(f"row {n}: no Embed")
            continue
        if embed in seen:
            errors.append(f"row {n}: embed {embed!r} appears twice")
        seen.add(embed)
        if key not in KEYS:
            errors.append(f"row {n} ({embed}): Key must be one of {', '.join(sorted(KEYS))}, not {key!r}")
        publish = [p.strip() for p in cell("Publish list").split(",") if p.strip()]
        blocked = [why for ok, why in [
            (cell("Sync").lower() in ("yes", "y", "true"), "Sync is not Yes"),
            (cell("Drive file ID"), "no Drive file ID"),
            (publish, "no publish list"),
            (cell("Approved by"), "no Approved by"),
            (cell("Approved on"), "no Approved on"),
        ] if not ok]
        sources.append({
            "embed": embed, "source": cell("Source"), "drive_file_id": cell("Drive file ID") or None,
            "shape": cell("Shape") or None, "key": key, "publish": publish,
            "approved_by": cell("Approved by") or None, "approved_on": cell("Approved on") or None,
            "publishable": not blocked, "blocked": blocked or None, "notes": cell("Notes") or None,
        })
    return sources, errors


def render(sources, origin):
    head = (f"# GENERATED by build/sync_site_map.py from {origin}. Do not edit: change the Site Map sheet.\n"
            "# Only sources with publishable: true may be published, and only their `publish` columns.\n")
    return head + yaml.safe_dump({"sources": sources}, sort_keys=False, allow_unicode=True, width=120)


def main():
    ap = argparse.ArgumentParser()
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--csv")
    src.add_argument("--sheet")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    rows = from_csv(a.csv) if a.csv else from_sheet(a.sheet)
    sources, errors = parse(rows)
    if errors:
        print("Site Map not synced:\n  " + "\n  ".join(errors), file=sys.stderr)
        return 1
    origin = "the Site Map sheet" if a.sheet else pathlib.Path(a.csv).name
    pathlib.Path(a.out).write_text(render(sources, origin))
    ok = [s["embed"] for s in sources if s["publishable"]]
    print(f"site-map: {len(sources)} sources, publishable: {', '.join(ok) or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
